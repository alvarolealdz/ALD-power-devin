@router.post("/{refund_id}", name="refunds_update")
def update_row(
    request: Request,
    session: DbSession,
    current_user: CurrentUser,
    refund_id: int,
    transaction_ref: Annotated[str, Form()] = "",
    customer_ref: Annotated[str, Form()] = "",
    amount: Annotated[str, Form()] = "",
    currency: Annotated[str, Form()] = "",
    reason: Annotated[str, Form()] = "",
    status: Annotated[str, Form()] = "",
    requested_on: Annotated[str, Form()] = "",
    approver_id: Annotated[str, Form()] = "",
):
    auth.require_write(current_user)
    admin = auth.is_admin(current_user)
    row = _get(session, refund_id)
    values, errors = _parse(
        {
            "transaction_ref": transaction_ref,
            "customer_ref": customer_ref,
            "amount": amount,
            "currency": currency,
            "reason": reason,
            "status": status,
            "requested_on": requested_on,
            "approver_id": approver_id,
        },
        admin,
    )
    _check_references(session, values, errors)
    if (
        WORKFLOW_FIELD in values
        and values[WORKFLOW_FIELD] != row.status
        and values[WORKFLOW_FIELD]
        not in STATUS_TRANSITIONS.get(
            row.status,
            tuple(option for option in STATUS_OPTIONS if option != row.status),
        )
    ):
        errors[WORKFLOW_FIELD] = "transition not allowed"
    if errors:
        return _form_page(
            request,
            session,
            values,
            errors,
            admin,
            action=str(request.url_for("refunds_update", refund_id=row.id)),
            heading=f"Edit refund {row.id}",
            delete_url=str(request.url_for("refunds_delete", refund_id=row.id)),
            detail_url=str(request.url_for("refunds_detail", refund_id=row.id)),
            row_id=row.id,
            status_code=400,
        )
    audit.update(session, row, values)
    return RedirectResponse(request.url_for("refunds_detail", refund_id=row.id), status_code=303)


