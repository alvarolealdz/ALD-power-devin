@router.post("", name="refunds_create")
def create_row(
    request: Request,
    session: DbSession,
    current_user: CurrentUser,
    transaction_ref: Annotated[str, Form()] = "",
    customer_ref: Annotated[str, Form()] = "",
    amount: Annotated[str, Form()] = "",
    currency: Annotated[str, Form()] = "",
    reason: Annotated[str, Form()] = "",
    status: Annotated[str, Form()] = "",
    requested_on: Annotated[str, Form()] = "",
    approver_id: Annotated[str, Form()] = "",
):
    auth.require_admin(current_user)
    admin = auth.is_admin(current_user)
    values, errors = _parse(
        {
            "transaction_ref": transaction_ref,
            "customer_ref": customer_ref,
            "amount": amount,
            "currency": currency,
            "reason": reason,
            "status": status,
            "requested_on": requested_on,
            "approver_id": approver_id,
        },
        admin,
    )
    _check_references(session, values, errors)
    if errors:
        return _form_page(
            request,
            session,
            values,
            errors,
            admin,
            action=str(request.url_for("refunds_create")),
            heading="New refund",
            status_code=400,
        )
    row = Refund(**values)
    audit.insert(session, row)
    return RedirectResponse(request.url_for("refunds_detail", refund_id=row.id), status_code=303)


@router.get("/{refund_id}", name="refunds_detail")
def detail_row(request: Request, session: DbSession, current_user: CurrentUser, refund_id: int):
    row = _get(session, refund_id)
    admin = auth.is_admin(current_user)
    current_value = row.status
    current = {
        "label": current_value,
        "tone": STATUS_TONES.get(current_value, "neutral"),
    }
    decisions = [
        {"label": option.title(), "value": option, "tone": STATUS_TONES.get(option, "neutral")}
        for option in STATUS_OPTIONS
        if option
        in STATUS_TRANSITIONS.get(
            current_value,
            tuple(option for option in STATUS_OPTIONS if option != current_value),
        )
    ]
    return templates.TemplateResponse(
        request,
        "refunds/detail.html",
        {
            "title": f"{SINGULAR} {row.id}",
            "row_id": row.id,
            "items": _items(row, admin),
            "list_url": str(request.url_for("refunds_list")),
            "edit_url": (
                str(request.url_for("refunds_edit", refund_id=row.id))
                if auth.can_write(current_user)
                else None
            ),
            "delete_url": (
                str(request.url_for("refunds_delete", refund_id=row.id))
                if auth.can_write(current_user)
                else None
            ),
            "current": current,
            "decisions": decisions,
            "decision_url": str(request.url_for("refunds_decide", refund_id=row.id)),
            "can_decide": auth.can_write(current_user),
        },
    )


@router.post("/{refund_id}/status", name="refunds_decide")
def decide_row(
    request: Request,
    session: DbSession,
    current_user: CurrentUser,
    refund_id: int,
    status: Annotated[str, Form()] = "",
    expected: Annotated[str, Form()] = "",
):
    auth.require_write(current_user)
    row = _get(session, refund_id)
    if expected and expected != row.status:
        raise HTTPException(
            status_code=409,
            detail=(
                f"this {SINGULAR} was already moved to {row.status} "
                "by someone else; reload to see it"
            ),
        )
    if status not in STATUS_OPTIONS:
        raise HTTPException(status_code=400, detail="invalid status")
    if status not in STATUS_TRANSITIONS.get(
        row.status,
        tuple(option for option in STATUS_OPTIONS if option != row.status),
    ):
        raise HTTPException(status_code=400, detail="transition not allowed")
    audit.update(session, row, {"status": status})
    return RedirectResponse(request.url_for("refunds_list"), status_code=303)


