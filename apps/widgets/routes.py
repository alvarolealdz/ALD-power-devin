@router.get("", name="widgets_list")
def list_rows(
    request: Request,
    session: DbSession,
    current_user: CurrentUser,
    state: str = "",
    q: str = "",
    sort: str = "",
    dir: str = "asc",
):
    admin = auth.is_admin(current_user)
    q = q.strip()
    searchable = _SEARCHABLE + (_ADMIN_SEARCHABLE if admin else ())
    sortable = _ADMIN_SORTABLE if admin else _SORTABLE
    normalized_sort = sort if sort in sortable else ""
    normalized_dir = dir if dir in {"asc", "desc"} else "asc"
    query = select(MODEL)
    if q and searchable:
        escaped = q.replace("\\", "\\\\").replace("%", "\\%").replace("_", "\\_")
        pattern = f"%{escaped}%"
        query = query.where(
            or_(*(getattr(MODEL, column).ilike(pattern, escape="\\") for column in searchable))
        )
    workflow_column = getattr(MODEL, WORKFLOW_FIELD)
    grouped = dict(
        session.execute(select(workflow_column, func.count()).group_by(workflow_column)).all()
    )
    open_count = sum(grouped.get(option, 0) for option in OPEN_STATES)
    total = sum(grouped.values())
    if state == "":
        query = query.where(workflow_column.in_(OPEN_STATES))
    elif state == "all":
        pass
    elif state in STATUS_OPTIONS:
        query = query.where(workflow_column == state)
    else:
        raise HTTPException(status_code=400, detail="invalid state")
    list_url = str(request.url_for("widgets_list"))
    tabs = [
        {"label": "Needs decision", "href": list_url, "count": open_count, "active": state == ""}
    ]
    tabs.extend(
        {
            "label": option.title(),
            "href": f"{list_url}?{urlencode({'state': option})}",
            "count": grouped.get(option, 0),
            "active": state == option,
        }
        for option in STATUS_OPTIONS
    )
    tabs.append(
        {
            "label": "All",
            "href": f"{list_url}?state=all",
            "count": total,
            "active": state == "all",
        }
    )
    today_start = datetime.now(UTC).replace(hour=0, minute=0, second=0, microsecond=0, tzinfo=None)
    decided_today = sum(
        1
        for entry in session.scalars(
            select(AuditLog).where(
                AuditLog.table_name == MODEL.__tablename__,
                AuditLog.action == AuditLog.ACTION_UPDATE,
                AuditLog.created_at >= today_start,
            )
        )
        if (entry.after or {}).get(WORKFLOW_FIELD) in STATUS_CLOSED
        and (entry.before or {}).get(WORKFLOW_FIELD) not in STATUS_CLOSED
        and (entry.after or {}).get(WORKFLOW_FIELD) != (entry.before or {}).get(WORKFLOW_FIELD)
    )
    if normalized_sort:
        sort_column = getattr(MODEL, normalized_sort)
        query = query.order_by(sort_column.asc() if normalized_dir == "asc" else sort_column.desc())
    elif state == "":
        query = query.order_by(MODEL.id.asc())
    else:
        query = query.order_by(MODEL.id.desc())
    rows = session.scalars(query).all()
    next_url = _next_url(request)
    new_url = str(request.url_for("widgets_new")) if auth.can_write(current_user) else None
    return templates.TemplateResponse(
        request,
        "widgets/list.html",
        {
            "title": TITLE,
            "columns": _columns(
                request,
                admin,
                state=state,
                q=q,
                sort=normalized_sort,
                direction=normalized_dir,
            ),
            "rows": [
                _row(request, row, admin, auth.can_write(current_user), next_url) for row in rows
            ],
            "actions": [{"label": "Edit", "href_key": "edit_url"}],
            "description": DESCRIPTION,
            "list_url": str(request.url_for("widgets_list")),
            "searchable": bool(_SEARCHABLE or (_ADMIN_SEARCHABLE if admin else ())),
            "q": q,
            "sort": normalized_sort,
            "dir": normalized_dir,
            "state": state,
            "empty": {
                "title": ("Nothing needs a decision" if state == "" else "No widgets yet"),
                "text": (
                    f"New {SINGULAR} will appear here when they arrive."
                    if state == ""
                    else DESCRIPTION or None
                ),
                "cta": {"label": "New Widget", "href": new_url} if new_url else None,
            },
            "new_url": new_url,
            "stats": [
                {"label": "Waiting", "value": open_count},
                {"label": "Decided today", "value": decided_today},
                {"label": "Total", "value": total},
            ],
            "tabs": tabs,
        },
    )


