@router.post("/{widget_id}", name="widgets_update")
def update_row(
    request: Request,
    session: DbSession,
    current_user: CurrentUser,
    widget_id: int,
    label: Annotated[str, Form()] = "",
    quantity: Annotated[str, Form()] = "",
    due_on: Annotated[str, Form()] = "",
    active: Annotated[str, Form()] = "",
    status: Annotated[str, Form()] = "",
    owner_id: Annotated[str, Form()] = "",
    internal_note: Annotated[str, Form()] = "",
):
    auth.require_write(current_user)
    admin = auth.is_admin(current_user)
    row = _get(session, widget_id)
    values, errors = _parse(
        {
            "label": label,
            "quantity": quantity,
            "due_on": due_on,
            "active": active,
            "status": status,
            "owner_id": owner_id,
            "internal_note": internal_note,
        },
        admin,
    )
    _check_references(session, values, errors)
    if (
        WORKFLOW_FIELD in values
        and values[WORKFLOW_FIELD] != row.status
        and values[WORKFLOW_FIELD]
        not in STATUS_TRANSITIONS.get(
            row.status,
            tuple(option for option in STATUS_OPTIONS if option != row.status),
        )
    ):
        errors[WORKFLOW_FIELD] = "transition not allowed"
    if errors:
        return _form_page(
            request,
            session,
            values,
            errors,
            admin,
            action=str(request.url_for("widgets_update", widget_id=row.id)),
            heading=f"Edit Widget {row.id}",
            delete_url=str(request.url_for("widgets_delete", widget_id=row.id)),
            detail_url=str(request.url_for("widgets_detail", widget_id=row.id)),
            row_id=row.id,
            status_code=400,
        )
    audit.update(session, row, values)
    return RedirectResponse(request.url_for("widgets_detail", widget_id=row.id), status_code=303)


